// Release signing: keystore.properties (storeFile / storePassword / keyAlias /
// keyPassword) is looked up next to this file, then in %LOCALAPPDATA%/Mfork
// (or $MFORK_KEYSTORE_PROPERTIES). Never committed; without it the release
// build is unsigned.
val keystoreProperties = Properties().apply {
    val candidates = listOfNotNull(
        System.getenv("MFORK_KEYSTORE_PROPERTIES")?.let { file(it) },
        file("keystore.properties"),
        System.getenv("LOCALAPPDATA")?.let { file("$it/Mfork/keystore.properties") },
    )
    candidates.firstOrNull { it.exists() }?.inputStream()?.use { load(it) }
}

